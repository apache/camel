package org.apache.camel.test.infra.openai.mock;

import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * In-memory state behind the Files and Batch APIs of the mock: the uploaded input files, the result files built for a
 * finished batch, and the batches themselves. Tests can read the uploaded content back to assert on the JSONL a route
 * produced.
 */
public class BatchStore {

    /**
     * A file uploaded by a route or generated by the mock for a finished batch.
     */
    public record StoredFile(String id, String filename, String purpose, byte[] content) {
    }

    /**
     * A created batch and the position it reached in the configured status progression.
     */
    public static class StoredBatch {
        final String id;
        final String inputFileId;
        final String endpoint;
        final String metadata;
        int statusIndex;
        boolean cancelling;
        boolean cancelled;
        boolean resultsBuilt;
        String outputFileId;
        String errorFileId;
        int total;
        int completed;
        int failed;

        StoredBatch(String id, String inputFileId, String endpoint, String metadata) {
            this.id = id;
            this.inputFileId = inputFileId;
            this.endpoint = endpoint;
            this.metadata = metadata;
        }
    }

    private final Map<String, StoredFile> files = new ConcurrentHashMap<>();
    private final Map<String, StoredBatch> batches = new ConcurrentHashMap<>();
    private final AtomicInteger sequence = new AtomicInteger();

    String addFile(String filename, String purpose, byte[] content) {
        String id = "file-mock-" + sequence.incrementAndGet();
        files.put(id, new StoredFile(id, filename, purpose, content));
        return id;
    }

    StoredBatch addBatch(String inputFileId, String endpoint, String metadata) {
        String id = "batch_mock_" + sequence.incrementAndGet();
        StoredBatch batch = new StoredBatch(id, inputFileId, endpoint, metadata);
        batches.put(id, batch);
        return batch;
    }

    StoredFile file(String id) {
        return files.get(id);
    }

    StoredBatch batch(String id) {
        return batches.get(id);
    }

    void removeFile(String id) {
        files.remove(id);
    }

    /**
     * Returns the content of an uploaded or generated file, or {@code null} when no such file exists.
     */
    public byte[] getFileContent(String id) {
        StoredFile file = files.get(id);
        return file != null ? file.content() : null;
    }

    /**
     * Returns the content of the single file uploaded so far, as the text a route sent. Fails when no file or more than
     * one was uploaded, so a test asserting on "the" input file cannot pass by accident.
     */
    public String getUploadedFile() {
        return new String(uploadedFile().content(), StandardCharsets.UTF_8);
    }

    /**
     * The name the route uploaded the batch input file under.
     */
    public String getUploadedFileName() {
        return uploadedFile().filename();
    }

    private StoredFile uploadedFile() {
        var uploaded = files.values().stream().filter(file -> "batch".equals(file.purpose())).toList();
        if (uploaded.size() != 1) {
            throw new IllegalStateException("Expected exactly one uploaded batch input file, found " + uploaded.size());
        }
        return uploaded.get(0);
    }

    void clear() {
        files.clear();
        batches.clear();
        sequence.set(0);
    }
}
