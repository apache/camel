package org.apache.camel.dsl.jbang.it;

import java.nio.file.Path;
import java.time.Duration;

import org.apache.camel.dsl.jbang.it.support.JBangTestSupport;
import org.awaitility.Awaitility;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.BindMode;
import org.testcontainers.containers.GenericContainer;
import org.testcontainers.containers.wait.strategy.Wait;
import org.testcontainers.utility.DockerImageName;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Integration test for exporting and deploying a Camel application as a WAR to an external Tomcat servlet container.
 */
@Tag("tomcat")
@Tag("container-only")
public class Tomcat10ExportITCase extends JBangTestSupport {

    private static final String EXPORT_DIRECTORY = "tomcat-export";
    private static final String ARTIFACT_ID = "camel-tomcat";
    private static final String WAR_NAME = ARTIFACT_ID + "-1.0-SNAPSHOT.war";
    private static final String ROUTE_STARTED = "CAMEL_TOMCAT_WAR_ROUTE_STARTED";

    @Test
    public void testTomcatWarExportAndDeployment() throws Exception {
        // Create a route that proves Camel starts and processes routes
        // after the generated WAR is deployed to external Tomcat.
        newFileInDataFolder("tomcat-route.camel.yaml", """
                - from:
                    uri: timer:tomcat?period=500&repeatCount=1
                    steps:
                      - log: CAMEL_TOMCAT_WAR_ROUTE_STARTED
                """);

        String exportDirectory = mountPoint() + "/" + EXPORT_DIRECTORY;
        String routeFile = mountPoint() + "/tomcat-route.camel.yaml";

        // Export the Camel project as a Tomcat-compatible WAR.
        execute(String.format(
                "export %s --runtime=tomcat --spring-boot-version=3.5.0 "
                              + "--gav=com.example:%s:1.0-SNAPSHOT "
                              + "--directory=%s",
                routeFile, ARTIFACT_ID, exportDirectory));

        // Verify the export generated the expected WAR configuration.
        assertFileInDataFolderContains(
                EXPORT_DIRECTORY + "/pom.xml",
                "<packaging>war</packaging>");

        assertFileInDataFolderContains(
                EXPORT_DIRECTORY + "/pom.xml",
                "<artifactId>spring-boot-starter-tomcat</artifactId>");

        assertFileInDataFolderContains(
                EXPORT_DIRECTORY + "/pom.xml",
                "<scope>provided</scope>");

        // Build the WAR inside the CLI Testcontainer. This uses the Maven
        // wrapper generated by camel export and the shared Maven repository.
        String buildOutput = execInContainer(
                "cd " + shellQuote(exportDirectory)
                                             + " && chmod +x ./mvnw"
                                             + " && ./mvnw -B -DskipTests package");

        assertThat(buildOutput)
                .as("Maven WAR build output")
                .contains("BUILD SUCCESS");

        // The CLI container writes into the host-mounted test data folder.
        Path war = Path.of(
                getDataFolder(),
                EXPORT_DIRECTORY,
                "target",
                WAR_NAME);

        assertThat(war)
                .as("Generated WAR")
                .exists()
                .isRegularFile();

        assertThat(war.toFile().length())
                .as("Generated WAR must not be empty")
                .isPositive();

        // Deploy the generated WAR to a real external Tomcat container.
        // The WAR is mounted under a stable name so its context path is
        // /camel-tomcat, independent of the Maven version suffix.
        String tomcatImage = System.getProperty(
                "tomcat.test.image",
                "tomcat:10.1-jdk21-temurin");

        try (GenericContainer<?> tomcat = new GenericContainer<>(
                DockerImageName.parse(tomcatImage))
                .withFileSystemBind(
                        war.toAbsolutePath().toString(),
                        "/usr/local/tomcat/webapps/" + ARTIFACT_ID + ".war",
                        BindMode.READ_ONLY)
                .withExposedPorts(8080)
                .waitingFor(
                        Wait.forHttp(
                                "/" + ARTIFACT_ID + "/actuator/health")
                                .forStatusCode(200)
                                .withStartupTimeout(Duration.ofMinutes(3)))) {

            tomcat.start();

            // The HTTP wait strategy verifies that Tomcat deployed the WAR
            // and that the Spring Boot application became healthy.
            assertThat(tomcat.isRunning()).isTrue();

            // Verify that Camel actually started the route inside Tomcat.
            Awaitility.await()
                    .atMost(Duration.ofSeconds(60))
                    .pollInterval(Duration.ofSeconds(1))
                    .untilAsserted(() -> assertThat(tomcat.getLogs())
                            .contains(ROUTE_STARTED));
        }
    }

    private static String shellQuote(String value) {
        return "'" + value.replace("'", "'\\''") + "'";
    }
}
