package org.apache.camel.dsl.jbang.core.commands.mcp;

import org.apache.camel.dsl.jbang.core.commands.CamelJBangMain;
import org.apache.camel.dsl.jbang.core.common.CliException;
import org.apache.camel.dsl.jbang.core.common.CliExitCode;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * camel mcp without JBang says what to do instead (CAMEL-26932).
 */
class McpCommandTest {

    @Test
    void withoutJBangSaysHowToRunTheServer() {
        McpCommand command = new McpCommand(new CamelJBangMain());
        command.jbang = "no-such-jbang-command-26932";
        command.version = "4.24.0";

        assertThatThrownBy(command::doCall)
                .isInstanceOfSatisfying(CliException.class,
                        e -> assertThat(e.getExitCode()).isEqualTo(CliExitCode.FAILURE))
                .hasMessageContaining("which is not installed")
                .hasMessageContaining("java -jar camel-jbang-mcp-4.24.0-runner.jar");
    }
}
