package org.apache.camel.component.sql;

import java.lang.reflect.Method;
import java.util.Map;
import java.util.Set;

import javax.sql.DataSource;

import org.apache.camel.CamelContext;
import org.apache.camel.Endpoint;
import org.apache.camel.spi.Metadata;
import org.apache.camel.spi.SecretRotationAware;
import org.apache.camel.spi.annotations.Component;
import org.apache.camel.support.HealthCheckComponent;
import org.apache.camel.support.PropertyBindingSupport;
import org.apache.camel.util.ObjectHelper;
import org.apache.camel.util.PropertiesHelper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * The <a href="http://camel.apache.org/sql-component.html">SQL Component</a> is for working with databases using JDBC
 * queries.
 */
@Component("sql")
public class SqlComponent extends HealthCheckComponent implements SecretRotationAware {

    private static final Logger LOG = LoggerFactory.getLogger(SqlComponent.class);

    @Metadata(autowired = true)
    private DataSource dataSource;
    @Metadata(label = "advanced", defaultValue = "true")
    private boolean usePlaceholder = true;
    @Metadata(label = "advanced", autowired = true)
    private RowMapperFactory rowMapperFactory;
    @Metadata(label = "advanced",
              description = "Whether to detect the network address location of the Database on startup."
                            + " This information is gathered via reflection on the DataSource, and is vendor specific."
                            + " This option can be used to turn this off.",
              defaultValue = "true")
    private boolean serviceLocationEnabled = true;
    @Metadata(label = "producer", defaultValue = "true",
              description = "Whether to optimize batch by turning off auto-commit which can dramatic improve performance, and instead execute as a manual commit after the entire batch operation is complete")
    private boolean batchAutoCommitDisabled = true;
    @Metadata(label = "advanced",
              description = "Gives the JDBC driver a hint as to the number of rows that should be fetched from the database when more rows are needed for ResultSet objects generated by this Statement. If the value specified is zero, then the hint is ignored. The default value is zero."
                            + " This is important for processing large result sets: Setting this higher than the default value will increase processing speed at the cost of memory consumption; setting this lower can avoid transferring row data that will never be read by the application.")
    private int fetchSize;
    @Metadata(label = "producer,security", defaultValue = "false", security = "insecure:dev", insecureValue = "true",
              description = "Whether to allow overriding the endpoint-configured SQL query with the CamelSqlQuery header."
                            + " Disabled by default; enable it only when the header source is trusted, since it lets a"
                            + " message choose the executed SQL. This is the default for all sql endpoints and can be"
                            + " overridden per endpoint.")
    private boolean allowQueryFromHeader;

    public SqlComponent() {
    }

    public SqlComponent(Class<? extends Endpoint> endpointClass) {
    }

    public SqlComponent(CamelContext context) {
        super(context);
    }

    public SqlComponent(CamelContext context, Class<? extends Endpoint> endpointClass) {
        super(context);
    }

    @Override
    protected Endpoint createEndpoint(String uri, String remaining, Map<String, Object> parameters) throws Exception {
        String query = getAndRemoveParameter(parameters, "query", String.class);
        if (query == null) {
            query = remaining;
        }
        if (ObjectHelper.isEmpty(query)) {
            throw new IllegalArgumentException("Query parameter is required");
        }
        String parameterPlaceholderSubstitute = getAndRemoveParameter(parameters, "placeholder", String.class, "#");
        if (usePlaceholder) {
            query = query.replaceAll(parameterPlaceholderSubstitute, "?");
        }
        String onConsume = getAndRemoveParameter(parameters, "consumer.onConsume", String.class);
        if (onConsume == null) {
            onConsume = getAndRemoveParameter(parameters, "onConsume", String.class);
        }
        if (onConsume != null && usePlaceholder) {
            onConsume = onConsume.replaceAll(parameterPlaceholderSubstitute, "?");
        }
        String onConsumeFailed = getAndRemoveParameter(parameters, "consumer.onConsumeFailed", String.class);
        if (onConsumeFailed == null) {
            onConsumeFailed = getAndRemoveParameter(parameters, "onConsumeFailed", String.class);
        }
        if (onConsumeFailed != null && usePlaceholder) {
            onConsumeFailed = onConsumeFailed.replaceAll(parameterPlaceholderSubstitute, "?");
        }
        String onConsumeBatchComplete = getAndRemoveParameter(parameters, "consumer.onConsumeBatchComplete", String.class);
        if (onConsumeBatchComplete == null) {
            onConsumeBatchComplete = getAndRemoveParameter(parameters, "onConsumeBatchComplete", String.class);
        }
        if (onConsumeBatchComplete != null && usePlaceholder) {
            onConsumeBatchComplete = onConsumeBatchComplete.replaceAll(parameterPlaceholderSubstitute, "?");
        }
        RowMapperFactory factory
                = getAndRemoveOrResolveReferenceParameter(parameters, "rowMapperFactory", RowMapperFactory.class);
        if (factory == null) {
            factory = rowMapperFactory;
        }

        // create endpoint
        SqlEndpoint endpoint = new SqlEndpoint(uri, this);
        endpoint.setBatchAutoCommitDisabled(isBatchAutoCommitDisabled());
        endpoint.setFetchSize(getFetchSize());
        endpoint.setServiceLocationEnabled(serviceLocationEnabled);
        endpoint.setAllowQueryFromHeader(isAllowQueryFromHeader());
        endpoint.setQuery(query);
        endpoint.setPlaceholder(parameterPlaceholderSubstitute);
        endpoint.setUsePlaceholder(isUsePlaceholder());
        endpoint.setOnConsume(onConsume);
        endpoint.setOnConsumeFailed(onConsumeFailed);
        endpoint.setOnConsumeBatchComplete(onConsumeBatchComplete);
        endpoint.setRowMapperFactory(factory);
        setProperties(endpoint, parameters);

        // endpoint configured data source takes precedence
        DataSource ds = dataSource;
        if (endpoint.getDataSource() != null) {
            ds = endpoint.getDataSource();
        }

        // create template
        JdbcTemplate jdbcTemplate = new JdbcTemplate(ds);
        Map<String, Object> templateOptions = PropertiesHelper.extractProperties(parameters, "template.");
        PropertyBindingSupport.bindProperties(getCamelContext(), jdbcTemplate, templateOptions);

        // set template on endpoint
        endpoint.setJdbcTemplate(jdbcTemplate);
        endpoint.setDataSource(ds);
        endpoint.setTemplateOptions(templateOptions);

        return endpoint;
    }

    @Override
    public void onSecretRotation(Object source) throws Exception {
        // Collect all DataSources this component can reach: the one injected directly (if any)
        // plus all DataSource beans registered in the registry. The registry beans are typically
        // not recreated during a route reload, so their connection pools still hold connections
        // that were authenticated with the old credentials.
        Set<DataSource> dataSources = getCamelContext().getRegistry().findByType(DataSource.class);
        if (this.dataSource != null) {
            dataSources.add(this.dataSource);
        }

        for (DataSource ds : dataSources) {
            evictDataSourceConnections(ds, source);
        }
    }

    /**
     * Evicts stale connections from the given DataSource so that the pool rebuilds them with the rotated credentials.
     * <p/>
     * HikariCP is tried first via reflection (so camel-sql does not need a compile-time dependency on it). Any
     * DataSource that does not expose a {@code softEvictConnections()} method is left untouched — the pool will pick up
     * the new credentials on its own reconnect cycle when existing connections expire.
     */
    static void evictDataSourceConnections(DataSource ds, Object source) {
        // HikariCP: softEvictConnections() marks all current connections for eviction while
        // allowing in-flight queries to complete; the pool then recreates them with the new credentials.
        try {
            Method softEvict = ds.getClass().getMethod("softEvictConnections");
            softEvict.invoke(ds);
            LOG.info("Secret rotation (source={}): HikariCP softEvictConnections() called on {}", source, ds);
            return;
        } catch (NoSuchMethodException e) {
            // Not a HikariCP DataSource — fall through to generic handling
        } catch (Exception e) {
            LOG.warn("Secret rotation (source={}): softEvictConnections() failed on {}: {}", source, ds, e.getMessage());
        }

        // Generic fallback: log that the pool was not explicitly evicted.
        // The pool will pick up the new credentials when existing connections expire naturally.
        LOG.info(
                "Secret rotation (source={}): DataSource {} does not expose softEvictConnections(); "
                 + "existing connections will be replaced as they expire or are validated",
                source, ds.getClass().getName());
    }

    /**
     * Sets the DataSource to use to communicate with the database.
     */
    public void setDataSource(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public DataSource getDataSource() {
        return dataSource;
    }

    /**
     * Sets whether to use placeholder and replace all placeholder characters with ? sign in the SQL queries.
     * <p/>
     * This option is default <tt>true</tt>
     */
    public void setUsePlaceholder(boolean usePlaceholder) {
        this.usePlaceholder = usePlaceholder;
    }

    public boolean isUsePlaceholder() {
        return usePlaceholder;
    }

    public RowMapperFactory getRowMapperFactory() {
        return rowMapperFactory;
    }

    /**
     * Factory for creating RowMapper
     */
    public void setRowMapperFactory(RowMapperFactory rowMapperFactory) {
        this.rowMapperFactory = rowMapperFactory;
    }

    public boolean isServiceLocationEnabled() {
        return serviceLocationEnabled;
    }

    /**
     * Whether to detect the network address location of the database on startup. This information is gathered via
     * reflection on the DataSource, and is vendor specific. This option can be used to turn this off.
     */
    public void setServiceLocationEnabled(boolean serviceLocationEnabled) {
        this.serviceLocationEnabled = serviceLocationEnabled;
    }

    public boolean isBatchAutoCommitDisabled() {
        return batchAutoCommitDisabled;
    }

    /**
     * Whether to optimize batch by turning off auto-commit which can dramatic improve performance, and instead execute
     * as a manual commit after the entire batch operation is complete
     */
    public void setBatchAutoCommitDisabled(boolean batchAutoCommitDisabled) {
        this.batchAutoCommitDisabled = batchAutoCommitDisabled;
    }

    public int getFetchSize() {
        return fetchSize;
    }

    public boolean isAllowQueryFromHeader() {
        return allowQueryFromHeader;
    }

    /**
     * Whether to allow overriding the endpoint-configured SQL query with the {@code CamelSqlQuery} header. Disabled by
     * default; this is the default for all sql endpoints and can be overridden per endpoint.
     */
    public void setAllowQueryFromHeader(boolean allowQueryFromHeader) {
        this.allowQueryFromHeader = allowQueryFromHeader;
    }

    /**
     * Gives the JDBC driver a hint as to the number of rows that should be fetched from the database when more rows are
     * needed for ResultSet objects generated by this Statement. If the value specified is zero, then the hint is
     * ignored. The default value is zero.
     *
     * This is important for processing large result sets: Setting this higher than the default value will increase
     * processing speed at the cost of memory consumption; setting this lower can avoid transferring row data that will
     * never be read by the application.
     */
    public void setFetchSize(int fetchSize) {
        this.fetchSize = fetchSize;
    }
}
