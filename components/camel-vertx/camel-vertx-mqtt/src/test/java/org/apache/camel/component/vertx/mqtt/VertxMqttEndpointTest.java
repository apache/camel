package org.apache.camel.component.vertx.mqtt;

import io.vertx.core.Vertx;
import io.vertx.mqtt.MqttClientOptions;
import org.apache.camel.CamelContext;
import org.apache.camel.ResolveEndpointFailedException;
import org.apache.camel.impl.DefaultCamelContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class VertxMqttEndpointTest {

    private CamelContext context;

    @BeforeEach
    void start() {
        context = new DefaultCamelContext();
        context.start();
    }

    @AfterEach
    void stop() {
        context.stop();
    }

    @Test
    void optionsFromTheUri() throws Exception {
        final VertxMqttEndpoint endpoint = context.getEndpoint(
                "vertx-mqtt:sensors/+/temp?brokerUrl=ssl://broker.example.com&mqttVersion=MQTT_3_1_1&qos=2"
                                                               + "&clientId=c1&cleanStart=false&manualAcksEnabled=true",
                VertxMqttEndpoint.class);
        final VertxMqttConfiguration configuration = endpoint.getConfiguration();
        assertEquals("sensors/+/temp", endpoint.getTopic());
        assertEquals(VertxMqttVersion.MQTT_3_1_1, configuration.getMqttVersion());
        assertEquals(2, configuration.getQos());
        assertEquals(new BrokerAddress("broker.example.com", 8883, true), endpoint.getBroker());

        final MqttClientOptions options = endpoint.createClientOptions();
        assertEquals("c1", options.getClientId());
        assertFalse(options.isAutoGeneratedClientId());
        assertFalse(options.isCleanSession());
        assertFalse(options.isAutoAck());
        assertEquals(4, options.getVersion());
        assertTrue(options.isSsl());
        assertEquals("HTTPS", options.getHostnameVerificationAlgorithm());
        assertFalse(options.isTrustAll());
    }

    @Test
    void defaults() throws Exception {
        final VertxMqttEndpoint endpoint = context.getEndpoint("vertx-mqtt:a/b", VertxMqttEndpoint.class);
        assertEquals(new BrokerAddress("localhost", 1883, false), endpoint.getBroker());
        final MqttClientOptions options = endpoint.createClientOptions();
        assertEquals(5, options.getVersion());
        assertEquals(1, endpoint.getConfiguration().getQos());
        assertTrue(options.isAutoGeneratedClientId());
        assertTrue(options.isAutoAck());
        assertFalse(options.isSsl());
        // Not the client default of -1, which means the 8092 bytes of the Netty decoder
        assertEquals(VertxMqttConstants.MAX_MESSAGE_SIZE, options.getMaxMessageSize());
        assertNull(options.getWillOptions().getTopic());
    }

    @Test
    void mqtt5OnlyOptionsAreLeftOutForMqtt3() throws Exception {
        final MqttClientOptions mqtt3 = context.getEndpoint(
                "vertx-mqtt:a?mqttVersion=MQTT_3_1_1&sessionExpiryInterval=60&receiveMaximum=5",
                VertxMqttEndpoint.class).createClientOptions();
        assertNull(mqtt3.getSessionExpireInterval());
        assertNull(mqtt3.getReceiveMaximum());
        final MqttClientOptions mqtt5 = context.getEndpoint("vertx-mqtt:a?sessionExpiryInterval=60&receiveMaximum=5",
                VertxMqttEndpoint.class).createClientOptions();
        assertEquals(60L, mqtt5.getSessionExpireInterval());
        assertEquals(5, mqtt5.getReceiveMaximum());
    }

    @Test
    void willMessage() throws Exception {
        final MqttClientOptions options = context.getEndpoint(
                "vertx-mqtt:a?willTopic=status/c1&willPayload=offline&willQos=1&willRetained=true",
                VertxMqttEndpoint.class).createClientOptions();
        assertEquals("status/c1", options.getWillOptions().getTopic());
        assertEquals("offline", options.getWillOptions().getMessageBytes().toString());
        assertEquals(1, options.getWillOptions().getQos());
        assertTrue(options.getWillOptions().isRetain());
    }

    @Test
    void anEndpointDoesNotChangeTheComponentConfiguration() {
        final VertxMqttComponent component = context.getComponent(VertxMqttConstants.SCHEME, VertxMqttComponent.class);
        context.getEndpoint("vertx-mqtt:a?qos=2", VertxMqttEndpoint.class);
        assertEquals(1, component.getConfiguration().getQos());
    }

    @Test
    void invalidOptionsFailTheEndpoint() {
        assertThrows(ResolveEndpointFailedException.class, () -> context.getEndpoint("vertx-mqtt:a?qos=3"));
        assertThrows(ResolveEndpointFailedException.class,
                () -> context.getEndpoint("vertx-mqtt:a?brokerUrl=ws://broker.example.com"));
        assertThrows(ResolveEndpointFailedException.class, () -> context.getEndpoint("vertx-mqtt:a?trustAll=true"));
    }

    @Test
    void theRegisteredVertxIsUsed() throws Exception {
        final Vertx vertx = Vertx.vertx();
        try (CamelContext other = new DefaultCamelContext()) {
            other.getRegistry().bind("vertx", vertx);
            other.start();
            final VertxMqttComponent component = other.getComponent(VertxMqttConstants.SCHEME, VertxMqttComponent.class);
            assertSame(vertx, component.getVertx());
        } finally {
            vertx.close();
        }
    }
}
