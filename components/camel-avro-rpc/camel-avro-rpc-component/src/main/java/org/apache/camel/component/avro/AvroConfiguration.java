package org.apache.camel.component.avro;

import java.net.URI;

import org.apache.avro.Protocol;
import org.apache.camel.RuntimeCamelException;
import org.apache.camel.spi.Metadata;
import org.apache.camel.spi.UriParam;
import org.apache.camel.spi.UriParams;
import org.apache.camel.spi.UriPath;
import org.apache.commons.lang3.StringUtils;

import static org.apache.camel.component.avro.AvroConstants.AVRO_MESSAGE_NAME_SEPARATOR;

@UriParams
public class AvroConfiguration implements Cloneable {

    @UriPath(description = "The transport: http or netty. With http, the consumer runs an Avro HTTP server on Jetty and the"
                           + " producer sends HTTP POST requests; with netty, both use the Avro Netty server and transceiver.")
    @Metadata(required = true)
    private AvroTransport transport;
    @UriPath(description = "The host name or IP address. The consumer binds its server to it, and the producer connects to it.")
    @Metadata(required = true)
    private String host;
    @UriPath(description = "The port number. The consumer listens on it, and the producer connects to it.")
    @Metadata(required = true)
    private int port;
    @UriPath(description = "The name of the protocol message to call or serve. The producer calls it unless the"
                           + " CamelAvroMessageName header is set. A consumer with a message name serves only that message; a"
                           + " consumer without one serves every message that no other consumer on the same host and port serves.")
    private String messageName;
    @UriParam(description = "Not used: the component does not read this option. Use protocol or protocolClassName instead.")
    private String protocolLocation;
    @UriParam(description = "The Avro protocol (org.apache.avro.Protocol) that defines the messages, such as the PROTOCOL field"
                            + " of a class generated by the Avro compiler. Set this option or protocolClassName: the endpoint"
                            + " fails to start without a protocol.")
    private Protocol protocol;
    @UriParam(description = "The fully qualified name of the class that defines the protocol. For a class generated by the Avro"
                            + " compiler, its static PROTOCOL field is used; for any other class or interface, Avro reflection"
                            + " builds the protocol and reflectionProtocol is turned on. Ignored when protocol is set.")
    private String protocolClassName;
    @UriParam(description = "The authority (host and port) of the endpoint URI, which the component sets from the URI."
                            + " Consumers with the same authority share one Avro server, created with the protocol of the first"
                            + " consumer that starts. A value set on the component is replaced by the authority of the endpoint URI.")
    private String uriAuthority;
    @UriParam(description = "Whether the protocol is a reflect protocol, built by Avro reflection from a Java interface, rather"
                            + " than one from classes generated by the Avro compiler. When true, the consumer and producer use the"
                            + " Avro reflect responder and requestor. Set it together with protocol: with protocolClassName it is"
                            + " turned on for a class without a PROTOCOL field.")
    private boolean reflectionProtocol;
    @UriParam(description = "Whether the consumer sets the message body to the one parameter of the called message, instead of"
                            + " an Object array of all parameters. The endpoint fails to start if the message, or any message of"
                            + " the protocol when messageName is not set, does not have exactly one parameter.")
    private boolean singleParameter;
    @UriParam(label = "security", security = "insecure:serialization")
    private String serializablePackages;

    public AvroConfiguration copy() {
        try {
            return (AvroConfiguration) clone();
        } catch (CloneNotSupportedException e) {
            throw new RuntimeCamelException(e);
        }
    }

    public void parseURI(URI uri) {
        transport = AvroTransport.valueOf(uri.getScheme());

        setHost(uri.getHost());
        setPort(uri.getPort());

        if (uri.getPath() != null
                && StringUtils.indexOf(uri.getPath(), AVRO_MESSAGE_NAME_SEPARATOR) != -1) {
            String path = StringUtils.substringAfter(uri.getPath(), AVRO_MESSAGE_NAME_SEPARATOR);
            if (!path.contains(AVRO_MESSAGE_NAME_SEPARATOR)) {
                setMessageName(path);
            } else {
                throw new IllegalArgumentException("Unrecognized Avro message name: " + path + " for uri: " + uri);
            }
        }

        setUriAuthority(uri.getAuthority());
    }

    public String getHost() {
        return host;
    }

    public void setHost(String host) {
        this.host = host;
    }

    public int getPort() {
        return port;
    }

    public void setPort(int port) {
        this.port = port;
    }

    public Protocol getProtocol() {
        return protocol;
    }

    public void setProtocol(Protocol protocol) {
        this.protocol = protocol;
    }

    public AvroTransport getTransport() {
        return transport;
    }

    public void setTransport(String transport) {
        this.transport = AvroTransport.valueOf(transport);
    }

    public void setTransport(AvroTransport transport) {
        this.transport = transport;
    }

    public String getProtocolLocation() {
        return protocolLocation;
    }

    public void setProtocolLocation(String protocolLocation) {
        this.protocolLocation = protocolLocation;
    }

    public String getProtocolClassName() {
        return protocolClassName;
    }

    public void setProtocolClassName(String protocolClassName) {
        this.protocolClassName = protocolClassName;
    }

    public String getMessageName() {
        return messageName;
    }

    public void setMessageName(String messageName) {
        this.messageName = messageName;
    }

    public String getUriAuthority() {
        return uriAuthority;
    }

    public void setUriAuthority(String uriAuthority) {
        this.uriAuthority = uriAuthority;
    }

    public boolean isReflectionProtocol() {
        return reflectionProtocol;
    }

    public void setReflectionProtocol(boolean isReflectionProtocol) {
        this.reflectionProtocol = isReflectionProtocol;
    }

    public boolean isSingleParameter() {
        return singleParameter;
    }

    public void setSingleParameter(boolean singleParameter) {
        this.singleParameter = singleParameter;
    }

    public String getSerializablePackages() {
        return serializablePackages;
    }

    /**
     * Comma-separated list of additional packages that contain trusted Avro model classes. Avro 1.12+ validates classes
     * resolved from schemas; Camel automatically trusts {@code org.apache.avro} for IPC and packages derived from the
     * configured protocol. Use this option for any additional model packages not inferred from the protocol.
     */
    public void setSerializablePackages(String serializablePackages) {
        this.serializablePackages = serializablePackages;
    }
}
