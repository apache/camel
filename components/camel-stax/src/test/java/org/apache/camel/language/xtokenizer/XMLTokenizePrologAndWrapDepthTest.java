package org.apache.camel.language.xtokenizer;

import org.apache.camel.builder.RouteBuilder;
import org.apache.camel.component.mock.MockEndpoint;
import org.apache.camel.support.builder.Namespaces;
import org.apache.camel.test.junit6.CamelTestSupport;
import org.junit.jupiter.api.Test;

/**
 * Valid XML that xtokenize must split: a document whose prolog has a comment or a doctype and no XML declaration, and
 * the wrap mode with a descendant path whose matches are at different depths.
 */
class XMLTokenizePrologAndWrapDepthTest extends CamelTestSupport {

    @Test
    void documentStartingWithACommentIsSplit() throws Exception {
        MockEndpoint mock = getMockEndpoint("mock:inject");
        mock.expectedBodiesReceived("<order>1</order>", "<order>2</order>");

        template.sendBody("direct:inject",
                "<!-- generated by the order export -->\n<orders><order>1</order><order>2</order></orders>");

        mock.assertIsSatisfied();
    }

    @Test
    void documentStartingWithADoctypeIsSplit() throws Exception {
        MockEndpoint mock = getMockEndpoint("mock:inject");
        mock.expectedBodiesReceived("<order>1</order>", "<order>2</order>");

        template.sendBody("direct:inject", "<!DOCTYPE orders>\n<orders><order>1</order><order>2</order></orders>");

        mock.assertIsSatisfied();
    }

    @Test
    void commentWithTheStartTagOfTheRootIsSplit() throws Exception {
        MockEndpoint mock = getMockEndpoint("mock:inject");
        mock.expectedBodiesReceived("<order>1</order>");

        template.sendBody("direct:inject", "<!-- the export starts with <orders> -->\n<orders><order>1</order></orders>");

        mock.assertIsSatisfied();
    }

    @Test
    void wrapModeWithMatchesAtDifferentDepths() throws Exception {
        MockEndpoint mock = getMockEndpoint("mock:wrap");
        mock.expectedBodiesReceived(
                "<orders><order>1</order></orders>",
                "<orders><box><order>2</order></box></orders>",
                "<orders><order>3</order></orders>");

        template.sendBody("direct:wrap",
                "<orders><order>1</order><box><order>2</order></box><order>3</order></orders>");

        mock.assertIsSatisfied();
    }

    @Test
    void wrapModeWithAContainerInAContainerOfTheSameName() throws Exception {
        MockEndpoint mock = getMockEndpoint("mock:wrap");
        mock.expectedBodiesReceived(
                "<orders><box><box><order>1</order></box></box></orders>",
                "<orders><order>2</order></orders>");

        template.sendBody("direct:wrap",
                "<orders><box><box><order>1</order></box></box><order>2</order></orders>");

        mock.assertIsSatisfied();
    }

    @Override
    protected RouteBuilder createRouteBuilder() {
        return new RouteBuilder() {
            @Override
            public void configure() {
                Namespaces none = new Namespaces();
                from("direct:inject").split().xtokenize("//order", 'i', none).to("mock:inject");
                from("direct:wrap").split().xtokenize("//order", 'w', none).to("mock:wrap");
            }
        };
    }
}
