import static org.apache.camel.utils.cassandra.CassandraUtils.generateTruncate;

/**
 * A Cassandra-based implementation of {@link KeyValueRepository} that stores key-value entries in a Cassandra table.
 * <p/>
 * Values are serialized to bytes using Java {@link ObjectOutputStream} and stored in a {@code BLOB} column. Keys are
 * stored as {@code TEXT}. Time-to-live is handled natively by Cassandra's {@code USING TTL} clause on {@code INSERT}
 * statements, so expired entries are removed automatically by Cassandra without any client-side eviction logic.
 * <p/>
 * All the write operations are implemented using Cassandra's lightweight transactions (LWT), so that they are ordered
 * with each other:
 * <ul>
 * <li>{@link #putIfAbsent(String, Object, Duration)} uses {@code INSERT ... IF NOT EXISTS}</li>
 * <li>{@link #put(String, Object, Duration)} uses {@code INSERT ... IF NOT EXISTS}, and when the key already exists
 * {@code UPDATE ... SET value = ? WHERE key = ? IF value = ?} with the value that has just been read, retried until it
 * succeeds</li>
 * <li>{@link #replace(String, Object, Object, Duration)} uses
 * {@code UPDATE ... SET value = ? WHERE key = ? IF value = ?}</li>
 * <li>{@link #delete(String, Object)} uses {@code DELETE FROM ... WHERE key = ? IF value = ?}</li>
 * <li>{@link #delete(String)} uses {@code DELETE FROM ... WHERE key = ? IF value = ?} with the value that has just been
 * read, retried until it succeeds</li>
 * </ul>
 * Mixing lightweight transactions with plain writes on the same row is not safe: the timestamp of a plain write is
 * generated by the client while the one of a lightweight transaction is generated by the server, so a plain write can
 * hide a lightweight transaction that has been applied. This is why a plain {@code INSERT} or {@code DELETE} is not
 * used. {@link #clear()} is not a lightweight transaction.
 * <p/>
 * An entry whose value expired (TTL) can leave its row behind without a value. Such a row is considered as absent.
 * <p/>
 * Advice: use LeveledCompaction for the backing table and tune read/write consistency levels for your use case.
 *
 * @since 4.23
 */
@Metadata(label = "bean",
          description = "A Cassandra-based KeyValueRepository that uses a Cassandra table to store key-value entries."
                        + " Advice: use LeveledCompaction for this table and tune read/write consistency levels.",
          annotations = { "interfaceName=org.apache.camel.spi.KeyValueRepository" })
@Configurer(metadataOnly = true)
@ManagedResource(description = "Cassandra based key-value repository")
public class CassandraKeyValueRepository extends ServiceSupport implements KeyValueRepository {

    private static final Logger LOGGER = LoggerFactory.getLogger(CassandraKeyValueRepository.class);

    private static final String KEY_COLUMN = "key";
    private static final String VALUE_COLUMN = "value";
    private static final String WRITE_TIME_ALIAS = "value_write_time";
    /**
     * Maximum number of attempts of a lightweight transaction loop, which only loops when another client wins a race
     */
    private static final int MAX_ATTEMPTS = 50;

    @Metadata(description = "Cassandra session", required = true)
    private CassandraSessionHolder session;
    @Metadata(description = "The table name for storing the data", defaultValue = "camel_keyvalue")
    private String table = "camel_keyvalue";
    @Metadata(description = "Write consistency level",
              enums = "ANY,ONE,TWO,THREE,QUORUM,ALL,LOCAL_ONE,LOCAL_QUORUM,EACH_QUORUM,SERIAL,LOCAL_SERIAL")
    private ConsistencyLevel writeConsistencyLevel;
    @Metadata(description = "Read consistency level",
              enums = "ANY,ONE,TWO,THREE,QUORUM,ALL,LOCAL_ONE,LOCAL_QUORUM,EACH_QUORUM,SERIAL,LOCAL_SERIAL")
    private ConsistencyLevel readConsistencyLevel;
    @Metadata(label = "advanced,security",
              description = "Sets an ObjectInputFilter pattern (jdk.serialFilter syntax) applied when deserializing"
                            + " values read back from the repository. When not set, the JVM-wide jdk.serialFilter is"
                            + " used if present; otherwise a conservative default filter denying java.net.* and"
                            + " otherwise allowing java.*, javax.* and org.apache.camel.* packages is applied. Widen"
                            + " this pattern when storing instances of your own classes in the repository.")
    private String deserializationFilter;

    private PreparedStatement selectStatement;
    private PreparedStatement selectAllKeysStatement;
    private PreparedStatement truncateStatement;
    private PreparedStatement insertIfNotExistsStatement;
    private PreparedStatement insertIfNotExistsWithTtlStatement;
    private PreparedStatement updateIfValueStatement;
    private PreparedStatement updateIfValueWithTtlStatement;
    private PreparedStatement deleteIfValueStatement;

    public CassandraKeyValueRepository() {
    }

    public CassandraKeyValueRepository(CqlSession session) {
        this.session = new CassandraSessionHolder(session);
    }

    // -------------------------------------------------------------------------
    // Helper methods

    /**
     * Checks whether a lightweight transaction was applied.
     *
     * @param  resultSet the result set from a conditional statement
     * @return           {@code true} if the statement was applied or the result is empty
     */
    protected final boolean isApplied(ResultSet resultSet) {
        Row row = resultSet.one();
        return row == null || row.getBoolean("[applied]");
    }

    // -------------------------------------------------------------------------
    // Lifecycle methods

    @Override
    protected void doStart() throws Exception {
        ObjectHelper.notNull(session, "session", this);
        session.start();
        initSelectStatement();
        initSelectAllKeysStatement();
        initClearStatement();
        initInsertIfNotExistsStatement();
        initInsertIfNotExistsWithTtlStatement();
        initUpdateIfValueStatement();
        initUpdateIfValueWithTtlStatement();
        initDeleteIfValueStatement();
    }

    @Override
    protected void doStop() throws Exception {
        if (session != null) {
            session.stop();
        }
    }

    // -------------------------------------------------------------------------
    // Prepared statement initialization

    protected void initSelectStatement() {
        Select select = generateSelect(table, new String[] { VALUE_COLUMN }, new String[] { KEY_COLUMN });
        SimpleStatement statement = applyConsistencyLevel(select.build(), readConsistencyLevel);
        LOGGER.debug("Generated Select {}", statement);
        selectStatement = getSession().prepare(statement);
    }

    protected void initSelectAllKeysStatement() {
        // the write time is null when the row has no value anymore (the value expired but not the row)
        Select select = selectFrom(table).column(KEY_COLUMN).writeTime(VALUE_COLUMN).as(WRITE_TIME_ALIAS);
        SimpleStatement statement = applyConsistencyLevel(select.build(), readConsistencyLevel);
        LOGGER.debug("Generated Select all keys {}", statement);
        selectAllKeysStatement = getSession().prepare(statement);
    }

    protected void initClearStatement() {
        Truncate truncate = generateTruncate(table);
        SimpleStatement statement = applyConsistencyLevel(truncate.build(), writeConsistencyLevel);
        LOGGER.debug("Generated truncate for clear operation {}", statement);
        truncateStatement = getSession().prepare(statement);
    }

    protected void initInsertIfNotExistsStatement() {
        SimpleStatement statement = applyConsistencyLevel(
                insertInto(table)
                        .value(KEY_COLUMN, bindMarker())
                        .value(VALUE_COLUMN, bindMarker())
                        .ifNotExists()
                        .build(),
                writeConsistencyLevel);
        LOGGER.debug("Generated Insert if not exists {}", statement);
        insertIfNotExistsStatement = getSession().prepare(statement);
    }

    protected void initInsertIfNotExistsWithTtlStatement() {
        SimpleStatement statement = applyConsistencyLevel(
                insertInto(table)
                        .value(KEY_COLUMN, bindMarker())
                        .value(VALUE_COLUMN, bindMarker())
                        .ifNotExists()
                        .usingTtl(bindMarker())
                        .build(),
                writeConsistencyLevel);
        LOGGER.debug("Generated Insert if not exists with TTL {}", statement);
        insertIfNotExistsWithTtlStatement = getSession().prepare(statement);
    }

    protected void initUpdateIfValueStatement() {
        // UPDATE table SET value = ? WHERE key = ? IF value = ?
        Update update = QueryBuilder.update(table)
                .setColumn(VALUE_COLUMN, bindMarker())
                .whereColumn(KEY_COLUMN).isEqualTo(bindMarker())
                .ifColumn(VALUE_COLUMN).isEqualTo(bindMarker());
        SimpleStatement statement = applyConsistencyLevel(update.build(), writeConsistencyLevel);
        LOGGER.debug("Generated Update if value {}", statement);
        updateIfValueStatement = getSession().prepare(statement);
    }

    protected void initUpdateIfValueWithTtlStatement() {
        // UPDATE table USING TTL ? SET value = ? WHERE key = ? IF value = ?
        Update update = QueryBuilder.update(table)
                .usingTtl(bindMarker())
                .setColumn(VALUE_COLUMN, bindMarker())
                .whereColumn(KEY_COLUMN).isEqualTo(bindMarker())
                .ifColumn(VALUE_COLUMN).isEqualTo(bindMarker());
        SimpleStatement statement = applyConsistencyLevel(update.build(), writeConsistencyLevel);
        LOGGER.debug("Generated Update if value with TTL {}", statement);
        updateIfValueWithTtlStatement = getSession().prepare(statement);
    }

    protected void initDeleteIfValueStatement() {
        // DELETE FROM table WHERE key = ? IF value = ?
        Delete delete = generateDelete(table, new String[] { KEY_COLUMN }, false)
                .ifColumn(VALUE_COLUMN).isEqualTo(bindMarker());
        SimpleStatement statement = applyConsistencyLevel(delete.build(), writeConsistencyLevel);
        LOGGER.debug("Generated Delete if value {}", statement);
        deleteIfValueStatement = getSession().prepare(statement);
    }

    // -------------------------------------------------------------------------
    // KeyValueRepository operations

    @Override
    @ManagedOperation(description = "Get value by key")
    public Object get(String key) {
        LOGGER.debug("Getting key {}", key);
        return deserialize(readValue(key));
    }

    /**
     * Stores a value with optional TTL.
     * <p/>
     * The value is stored with lightweight transactions, so that it is ordered with the other write operations, and the
     * returned previous value is the one that has actually been replaced.
     */
    @Override
    @ManagedOperation(description = "Put a key-value pair with optional TTL")
    public Object put(String key, Object value, Duration ttl) {
        LOGGER.debug("Putting key {} with TTL {}", key, ttl);
        ByteBuffer serializedValue = KeyValueRepositoryHelper.serializeToByteBuffer(value);
        int ttlSeconds = toTtlSeconds(ttl);
        for (int attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
            Row existing = insertIfNotExists(key, serializedValue, ttlSeconds);
            if (existing == null) {
                return null;
            }
            ByteBuffer previous = existing.getByteBuffer(VALUE_COLUMN);
            if (updateIfValue(key, serializedValue, previous, ttlSeconds)) {
                return deserialize(previous);
            }
            // another client changed the entry in between, try again
        }
        throw new IllegalStateException("Unable to put the key " + key + " after " + MAX_ATTEMPTS + " attempts");
    }

    /**
     * Removes an entry.
     * <p/>
     * The entry is removed with a lightweight transaction, so that it is ordered with the other write operations, and
     * the returned previous value is the one that has actually been removed.
     */
    @Override
    @ManagedOperation(description = "Delete a key")
    public Object delete(String key) {
        LOGGER.debug("Deleting key {}", key);
        ByteBuffer previous = readValue(key);
        for (int attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
            Row row = getSession().execute(deleteIfValueStatement.bind(key, previous)).one();
            if (row == null || row.getBoolean("[applied]")) {
                return deserialize(previous);
            }
            // another client changed the entry in between, try again with the value it has now
            previous = row.getByteBuffer(VALUE_COLUMN);
        }
        throw new IllegalStateException("Unable to delete the key " + key + " after " + MAX_ATTEMPTS + " attempts");
    }

    @Override
    @ManagedOperation(description = "Check if key exists")
    public boolean contains(String key) {
        LOGGER.debug("Checking key {}", key);
        return readValue(key) != null;
    }

    @Override
    public Set<String> keys() {
        LOGGER.debug("Getting all keys from table {}", table);
        ResultSet rs = getSession().execute(selectAllKeysStatement.bind());
        Set<String> result = new LinkedHashSet<>();
        for (Row row : rs) {
            if (!row.isNull(WRITE_TIME_ALIAS)) {
                result.add(row.getString(KEY_COLUMN));
            }
        }
        return Collections.unmodifiableSet(result);
    }

    @Override
    @ManagedOperation(description = "Clear all entries")
    public void clear() {
        LOGGER.debug("Clear table {}", table);
        getSession().execute(truncateStatement.bind());
    }

    /**
     * Atomically stores the value under the given key only if no mapping already exists, using Cassandra's lightweight
     * transaction ({@code INSERT ... IF NOT EXISTS}).
     *
     * @param  key   the key
     * @param  value the value to store
     * @param  ttl   the time-to-live; {@code null}, zero, or negative means no expiration
     * @return       the existing value if the key was already present, or {@code null} if the put succeeded
     */
    @Override
    public Object putIfAbsent(String key, Object value, Duration ttl) {
        LOGGER.debug("Putting key {} if absent with TTL {}", key, ttl);
        ByteBuffer serializedValue = KeyValueRepositoryHelper.serializeToByteBuffer(value);
        int ttlSeconds = toTtlSeconds(ttl);
        for (int attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
            Row existing = insertIfNotExists(key, serializedValue, ttlSeconds);
            if (existing == null) {
                return null;
            }
            ByteBuffer existingValue = existing.getByteBuffer(VALUE_COLUMN);
            if (existingValue != null) {
                return deserialize(existingValue);
            }
            // the row exists without a value, which is the same as absent: set the value if it is still not set
            if (updateIfValue(key, serializedValue, null, ttlSeconds)) {
                return null;
            }
            // another client set the value in between, try again
        }
        throw new IllegalStateException("Unable to put the key " + key + " after " + MAX_ATTEMPTS + " attempts");
    }

    /**
     * Atomically replaces the value for the given key only if the current value equals the expected old value, using
     * Cassandra's lightweight transaction ({@code UPDATE ... SET value = ? WHERE key = ? IF value = ?}).
     * <p/>
     * <b>Note:</b> the comparison is performed server-side on the <em>serialized</em> byte representation of the value,
     * not via {@link java.util.Objects#equals(Object, Object)} on the deserialized objects (as the default SPI
     * implementation does). Two objects that are {@code .equals()} but serialize to different bytes (e.g. maps/sets
     * with non-deterministic iteration order) would cause this method to return {@code false} where the default
     * implementation would return {@code true}.
     *
     * @param  expectedOldValue the value that must currently be associated with the key
     * @param  newValue         the new value to store
     * @param  ttl              the time-to-live for the new entry; {@code null}, zero, or negative means no expiration
     * @return                  {@code true} if the value was replaced, {@code false} if the current value did not match
     */
    @Override
    public boolean replace(String key, Object expectedOldValue, Object newValue, Duration ttl) {
        LOGGER.debug("Replacing key {} if value matches, TTL {}", key, ttl);
        ByteBuffer serializedNewValue = KeyValueRepositoryHelper.serializeToByteBuffer(newValue);
        ByteBuffer serializedExpectedValue = KeyValueRepositoryHelper.serializeToByteBuffer(expectedOldValue);
        return updateIfValue(key, serializedNewValue, serializedExpectedValue, toTtlSeconds(ttl));
    }

    /**
     * Atomically removes the entry for the given key only if the current value equals the expected value, using
     * Cassandra's lightweight transaction ({@code DELETE FROM ... WHERE key = ? IF value = ?}).
     * <p/>
     * <b>Note:</b> the comparison is performed server-side on the <em>serialized</em> byte representation of the value,
     * not via {@link java.util.Objects#equals(Object, Object)} on the deserialized objects (as the default SPI
     * implementation does). Two objects that are {@code .equals()} but serialize to different bytes (e.g. maps/sets
     * with non-deterministic iteration order) would cause this method to return {@code false} where the default
     * implementation would return {@code true}.
     *
     * @param  key           the key to remove
     * @param  expectedValue the value that must currently be associated with the key
     * @return               {@code true} if the entry was removed, {@code false} if the current value did not match or
     *                       the key was not present
     */
    @Override
    public boolean delete(String key, Object expectedValue) {
        LOGGER.debug("Deleting key {} if value matches", key);
        ByteBuffer serializedExpectedValue = KeyValueRepositoryHelper.serializeToByteBuffer(expectedValue);
        // bind order: key (WHERE), expectedValue (IF)
        ResultSet rs = getSession().execute(deleteIfValueStatement.bind(key, serializedExpectedValue));
        return isApplied(rs);
    }

    @Override
    @ManagedAttribute(description = "The number of entries in the repository")
    public int size() {
        return keys().size();
    }

    /**
     * Reads the serialized value of the key.
     *
     * @return the serialized value, or {@code null} if the key is absent or has no value anymore
     */
    private ByteBuffer readValue(String key) {
        Row row = getSession().execute(selectStatement.bind(key)).one();
        return row != null ? row.getByteBuffer(VALUE_COLUMN) : null;
    }

    private Object deserialize(ByteBuffer buffer) {
        return buffer != null ? KeyValueRepositoryHelper.deserialize(buffer, deserializationFilter) : null;
    }

    /**
     * Inserts the entry if the key does not exist.
     *
     * @return {@code null} if the entry has been inserted, otherwise the existing row, whose value is {@code null} if
     *         the row has no value
     */
    private Row insertIfNotExists(String key, ByteBuffer serializedValue, int ttlSeconds) {
        ResultSet rs;
        if (ttlSeconds > 0) {
            rs = getSession().execute(insertIfNotExistsWithTtlStatement.bind(key, serializedValue, ttlSeconds));
        } else {
            rs = getSession().execute(insertIfNotExistsStatement.bind(key, serializedValue));
        }
        Row row = rs.one();
        return row == null || row.getBoolean("[applied]") ? null : row;
    }

    /**
     * Sets the value if the current one equals the expected one, where a {@code null} expected value matches a key
     * without a value.
     */
    private boolean updateIfValue(String key, ByteBuffer serializedNewValue, ByteBuffer expectedValue, int ttlSeconds) {
        ResultSet rs;
        if (ttlSeconds > 0) {
            // bind order: TTL, newValue (SET), key (WHERE), expectedValue (IF)
            rs = getSession().execute(
                    updateIfValueWithTtlStatement.bind(ttlSeconds, serializedNewValue, key, expectedValue));
        } else {
            // bind order: newValue (SET), key (WHERE), expectedValue (IF)
            rs = getSession().execute(updateIfValueStatement.bind(serializedNewValue, key, expectedValue));
        }
        return isApplied(rs);
    }

    private static int toTtlSeconds(Duration ttl) {
        if (ttl == null || ttl.isZero() || ttl.isNegative()) {
            return 0;
        }
        return (int) ttl.toSeconds();
    }

    // -------------------------------------------------------------------------
    // Getters & Setters

    public CqlSession getSession() {
        return session.getSession();
    }

    public void setSession(CqlSession session) {
        this.session = new CassandraSessionHolder(session);
    }

    public String getTable() {
        return table;
    }

    public void setTable(String table) {
        this.table = table;
    }

    public ConsistencyLevel getWriteConsistencyLevel() {
        return writeConsistencyLevel;
    }

    public void setWriteConsistencyLevel(ConsistencyLevel writeConsistencyLevel) {
        this.writeConsistencyLevel = writeConsistencyLevel;
    }

    public ConsistencyLevel getReadConsistencyLevel() {
        return readConsistencyLevel;
    }

    public void setReadConsistencyLevel(ConsistencyLevel readConsistencyLevel) {
        this.readConsistencyLevel = readConsistencyLevel;
    }

    public String getDeserializationFilter() {
        return deserializationFilter;
    }

    /**
     * Sets an {@link java.io.ObjectInputFilter} pattern (same syntax as {@code jdk.serialFilter}) applied when
     * deserializing values read back from the repository. When not set, the JVM-wide {@code jdk.serialFilter} is used
     * if present, otherwise a conservative default filter is applied. Widen this pattern when storing instances of your
     * own classes in the repository.
     */
    public void setDeserializationFilter(String deserializationFilter) {
        this.deserializationFilter = deserializationFilter;
    }
}
