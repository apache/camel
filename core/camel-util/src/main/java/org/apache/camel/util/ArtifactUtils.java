    private static String hint(String name, String kind, Map<String, String> table) {
        if (name == null || name.isBlank()) {
            return "";
        }
        String artifact = table.get(name);
        if (artifact != null) {
            return " (the " + name + " " + kind + " is in " + artifact + "; " + dependencyHint(artifact) + ")";
        }
        String best = closest(name, table.keySet());
        if (best != null) {
            return " (not a built-in Camel " + kind + "; did you mean '" + best + "'?)";
        }
        return " (not a built-in Camel " + kind + ")";
    }

    /**
     * The candidate closest to the name, case-insensitively, when it is within a few edits (one for names up to three
     * characters, two, or a third of the name's length for longer names). Of candidates at the same distance the one
     * sharing the longer prefix with the name wins, as typos are seldom in the first letters (htps is https, not ftps);
     * when that still ties there is no answer, as a wrong guess is worse than none.
     *
     * @return the closest candidate, or null if none is close enough or the closest is ambiguous
     */
    public static String closest(String name, Collection<String> candidates) {
        if (name == null || name.isBlank() || candidates == null) {
            return null;
        }
        String best = null;
        int bestDistance = Integer.MAX_VALUE;
        int bestPrefix = -1;
        boolean tie = false;
        int threshold = name.length() <= 3 ? 1 : Math.max(2, name.length() / 3);
        String n = name.toLowerCase(Locale.ROOT);
        for (String candidate : candidates) {
            if (candidate == null) {
                continue;
            }
            String c = candidate.toLowerCase(Locale.ROOT);
            int d = distance(n, c);
            if (d > threshold || d > bestDistance) {
                continue;
            }
            int prefix = commonPrefix(n, c);
            if (d < bestDistance || prefix > bestPrefix) {
                best = candidate;
                bestDistance = d;
                bestPrefix = prefix;
                tie = false;
            } else if (prefix == bestPrefix) {
                tie = true;
            }
        }
        return tie ? null : best;
    }

    private static int commonPrefix(String a, String b) {
        int max = Math.min(a.length(), b.length());
        int i = 0;
        while (i < max && a.charAt(i) == b.charAt(i)) {
            i++;
        }
        return i;
    }

    /**
     * The Damerau-Levenshtein distance (optimal string alignment): insertions, deletions, substitutions and
     * transpositions of adjacent characters each count as one edit.
     */
    static int distance(String a, String b) {
        int n = a.length();
        int m = b.length();
        if (n == 0) {
            return m;
        }
        if (m == 0) {
            return n;
        }
        int[][] d = new int[n + 1][m + 1];
        for (int i = 0; i <= n; i++) {
            d[i][0] = i;
        }
        for (int j = 0; j <= m; j++) {
            d[0][j] = j;
        }
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                int cost = a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1;
                d[i][j] = Math.min(Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1), d[i - 1][j - 1] + cost);
                if (i > 1 && j > 1 && a.charAt(i - 1) == b.charAt(j - 2) && a.charAt(i - 2) == b.charAt(j - 1)) {
                    d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
                }
            }
        }
        return d[n][m];
    }

