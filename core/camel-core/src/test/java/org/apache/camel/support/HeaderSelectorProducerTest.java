package org.apache.camel.support;

import org.apache.camel.AsyncCallback;
import org.apache.camel.ContextTestSupport;
import org.apache.camel.Endpoint;
import org.apache.camel.Exchange;
import org.apache.camel.Message;
import org.apache.camel.Producer;
import org.apache.camel.spi.InvokeOnHeaderStrategy;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * A producer that picks its method by a header tells an unknown value from a void method: the strategies return
 * {@link InvokeOnHeaderStrategy#NO_METHOD} for a value they have no method for.
 */
public class HeaderSelectorProducerTest extends ContextTestSupport {

    private static final String HEADER = "MyAction";

    @Test
    public void testMethodWithResult() throws Exception {
        Exchange exchange = process(new ChildProducer(endpoint(), null), "HELLO", "World");

        assertNull(exchange.getException());
        assertEquals("Hello World", exchange.getMessage().getBody());
    }

    @Test
    public void testMethodOfTheParentStrategy() throws Exception {
        Exchange exchange = process(new ChildProducer(endpoint(), null), "BASE", "World");

        assertNull(exchange.getException());
        assertEquals("Base World", exchange.getMessage().getBody());
    }

    @Test
    public void testVoidMethodDoesNotRunTheParentStrategy() throws Exception {
        Exchange exchange = process(new ChildProducer(endpoint(), null), "VOID", "World");

        assertNull(exchange.getException());
        assertEquals("World", exchange.getMessage().getBody());
        assertEquals("child", exchange.getMessage().getHeader("ranBy"));
    }

    @Test
    public void testUnknownValueOfTheHeaderFails() throws Exception {
        Exchange exchange = process(new ChildProducer(endpoint(), null), "NOSUCH", "World");

        IllegalArgumentException e = assertInstanceOf(IllegalArgumentException.class, exchange.getException());
        assertEquals("Unsupported value NOSUCH of header MyAction", e.getMessage());
        assertEquals("World", exchange.getMessage().getBody());
    }

    @Test
    public void testUnknownDefaultValueFails() throws Exception {
        Exchange exchange = process(new ChildProducer(endpoint(), "NOSUCH"), null, "World");

        IllegalArgumentException e = assertInstanceOf(IllegalArgumentException.class, exchange.getException());
        assertEquals("Unsupported value NOSUCH configured on the endpoint (header MyAction is not set)", e.getMessage());
    }

    @Test
    public void testUnknownValueOfAStrategyFromOlderToolingDoesNothing() throws Exception {
        // a strategy generated by older tooling returns null for an unknown value, as for a void method
        Exchange exchange = process(new LegacyProducer(endpoint()), "NOSUCH", "World");

        assertNull(exchange.getException());
        assertEquals("World", exchange.getMessage().getBody());
    }

    private Endpoint endpoint() {
        return context.getEndpoint("mock:result");
    }

    private Exchange process(Producer producer, String action, Object body) throws Exception {
        ((HeaderSelectorProducer) producer).setCamelContext(context);
        producer.start();
        try {
            Exchange exchange = new DefaultExchange(context);
            if (action != null) {
                exchange.getMessage().setHeader(HEADER, action);
            }
            exchange.getMessage().setBody(body);
            producer.process(exchange);
            return exchange;
        } finally {
            producer.stop();
        }
    }

    public static class BaseProducer extends HeaderSelectorProducer {

        public BaseProducer(Endpoint endpoint, String defaultValue) {
            super(endpoint, HEADER, defaultValue);
        }

        public String onBase(Message message) {
            return "Base " + message.getBody();
        }

        public void onBaseVoid(Message message) {
            message.setHeader("ranBy", "base");
        }
    }

    public static class ChildProducer extends BaseProducer {

        public ChildProducer(Endpoint endpoint, String defaultValue) {
            super(endpoint, defaultValue);
        }

        public String onHello(Message message) {
            return "Hello " + message.getBody();
        }

        public void onVoid(Message message) {
            message.setHeader("ranBy", "child");
        }
    }

    public static class LegacyProducer extends HeaderSelectorProducer {

        public LegacyProducer(Endpoint endpoint) {
            super(endpoint, HEADER);
        }

        public String onHello(Message message) {
            return "Hello " + message.getBody();
        }
    }

    /**
     * As generated for {@link BaseProducer}.
     */
    public static class BaseProducerStrategy implements InvokeOnHeaderStrategy {

        @Override
        public Object invoke(Object obj, String key, Exchange exchange, AsyncCallback callback) {
            BaseProducer target = (BaseProducer) obj;
            switch (key) {
                case "BASE":
                    return target.onBase(exchange.getMessage());
                case "VOID":
                    target.onBaseVoid(exchange.getMessage());
                    return null;
                default:
                    return NO_METHOD;
            }
        }
    }

    /**
     * As generated for {@link ChildProducer}.
     */
    public static class ChildProducerStrategy implements InvokeOnHeaderStrategy {

        @Override
        public Object invoke(Object obj, String key, Exchange exchange, AsyncCallback callback) {
            ChildProducer target = (ChildProducer) obj;
            switch (key) {
                case "HELLO":
                    return target.onHello(exchange.getMessage());
                case "VOID":
                    target.onVoid(exchange.getMessage());
                    return null;
                default:
                    return NO_METHOD;
            }
        }
    }

    /**
     * As generated by tooling older than {@link InvokeOnHeaderStrategy#NO_METHOD}.
     */
    public static class LegacyProducerStrategy implements InvokeOnHeaderStrategy {

        @Override
        public Object invoke(Object obj, String key, Exchange exchange, AsyncCallback callback) {
            LegacyProducer target = (LegacyProducer) obj;
            switch (key) {
                case "HELLO":
                    return target.onHello(exchange.getMessage());
                default:
                    return null;
            }
        }
    }
}
